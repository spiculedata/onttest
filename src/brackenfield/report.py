"""Human outputs: Priya's list, the checks document, and CSV copies of the tables."""

from __future__ import annotations

from pathlib import Path

import polars as pl

SEVERITY_ORDER = {"error": 0, "warning": 1, "info": 2}


def priya_list(issues: pl.DataFrame) -> pl.DataFrame:
    return (
        issues.filter(pl.col("for_priya"))
        .with_columns(pl.col("severity").replace_strict(SEVERITY_ORDER).alias("_order"))
        .sort("_order", "check_id", "source_tab", "source_row", "entity_key", nulls_last=True)
        .drop("_order")
        .with_row_index("item", offset=1)
    )


def render_mdm_markdown(usage: pl.DataFrame) -> str:
    lines = ["# Term mapping (MDM)", "", "Every coded value found in the workbook and what it was normalised to. "
             "Edit `mdm/aliases.csv` to confirm or correct a mapping; the next run applies it.", "",
             "| Domain | Written as | Normalised to | How | Lines | Confirm? |", "|---|---|---|---|---|---|"]
    for r in usage.iter_rows(named=True):
        how = r["basis"] or "no match"
        if r["basis"] == "fuzzy":
            how = f"typo match {r['score']} on '{r['matched_on']}'"
        elif r["basis"] and r["matched_on"] and r["matched_on"] != r["raw_value"]:
            how = f"{r['basis']} ('{r['matched_on']}')"
        lines.append(f"| {r['domain']} | {_md_cell(r['raw_value'])} | {_md_cell(r['canonical'] or '—')} | {_md_cell(how)} | "
                     f"{r['line_count']} | {'yes' if r['needs_confirmation'] else ''} |")
    return "\n".join(lines)


def _md_cell(value: object) -> str:
    return "" if value is None else str(value).replace("|", "\\|").replace("\n", " ")


def _where(row: dict) -> str:
    if row["source_tab"] and row["source_row"]:
        return f"{row['source_tab']}!{row['source_row']}"
    return row["source_tab"] or ""


def render_priya_markdown(items: pl.DataFrame, as_of: str, run_id: str) -> str:
    lines = [
        "# For Priya: things the pipeline could not resolve",
        "",
        f"Register as of {as_of}. Pipeline run `{run_id}`. {items.height} item(s).",
        "Each item names the tab and row it came from. Nothing listed here was dropped; "
        "the record is in the database with the value as written.",
        "",
    ]
    for (check_id, title), group in items.group_by("check_id", "check_title", maintain_order=True):
        severity = group["severity"][0]
        lines += [f"## {check_id} ({severity}): {title}", "", "| # | Where | Record | Written as | What we found |", "|---|---|---|---|---|"]
        for row in group.iter_rows(named=True):
            lines.append(
                f"| {row['item']} | {_md_cell(_where(row))} | {_md_cell(row['entity_key'])} | "
                f"{_md_cell(row['raw_value'])} | {_md_cell(row['message'])} |"
            )
        lines.append("")
    return "\n".join(lines)


def render_checks_markdown(catalogue: pl.DataFrame, results: pl.DataFrame) -> str:
    counts = dict(results.iter_rows())
    lines = [
        "# Data quality checks",
        "",
        "Generated by `brackenfield run` from the check registry and the pandera contracts. Do not edit by hand.",
        "",
        "Severity: **error** = wrong or unusable as written (goes to Priya); **warning** = readable but suspicious "
        "(goes to Priya); **info** = handled automatically by a documented rule (logged only).",
        "",
    ]
    for kind, heading in (("rule", "Rule checks"), ("contract", "Table contracts (pandera)")):
        part = catalogue.filter(pl.col("kind") == kind)
        lines += [f"## {heading}", "", "| Check | Entity | Severity | Rule | Why | Last run |", "|---|---|---|---|---|---|"]
        for row in part.iter_rows(named=True):
            hits = counts.get(row["check_id"], 0)
            lines.append(
                f"| {row['check_id']} | {row['entity']} | {row['severity']} | {_md_cell(row['title'])} | "
                f"{_md_cell(row['rationale'])} | {'pass' if hits == 0 else f'{hits} hit(s)'} |"
            )
        lines.append("")
    return "\n".join(lines)


PERSONAL_COLUMNS = {"operator_mobile"}  # hidden column K: kept in DuckDB, not copied into loose CSVs


def export_tables(tables: dict[str, pl.DataFrame], directory: Path) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    for name, frame in tables.items():
        flat = frame.drop([c for c in frame.columns if c in PERSONAL_COLUMNS])
        flat = flat.with_columns(pl.col(pl.Datetime).dt.to_string("%Y-%m-%dT%H:%M:%S%z"))
        flat.write_csv(directory / f"{name}.csv")


ACTIVE_MACHINE_STATUSES = ("available", "on_project", "workshop")


def _sync_section(result) -> list[str]:
    sync = result.sync
    if not sync.refreshed:
        return ["## FieldTrax sync", "", f"Not refreshed this run: {sync.failure}. Devices and readings come from "
                "the last successful sync.", ""]
    c, st = sync.counts, sync.stats
    return [
        "## FieldTrax sync", "",
        f"- Devices listed: {c['devices_listed']}; readings received: {c['readings_received']}",
        f"- New reading lines stored: {c['new_readings']}; new device versions stored: {c['new_device_versions']}",
        f"- Items that could not be stored or fetched: {c['errors']} (see dq checks DV009/DV010/DV011)",
        f"- Requests: {st['requests']} (rate-limited and retried: {st['rate_limited']}, unavailable and retried: "
        f"{st['unavailable']}, network errors retried: {st['transport_errors']}, unreadable pages retried: "
        f"{st['bad_pages']}, signed in again: {st['reauths']})", "",
    ]


def _short_time(column: str) -> pl.Expr:
    return pl.col(column).str.slice(0, 16).str.replace("T", " ") + pl.lit(" UTC")


def _readings_changes(rows: pl.DataFrame) -> list[str]:
    """Readings changes grouped by pattern, so 84 devices with the same two new readings is one line."""
    parts = pl.col("record_key").str.split(" | ")
    per_device = (
        rows.with_columns(parts.list.get(0).alias("device_id"), parts.list.get(2).alias("time"))
        .group_by("device_id", "change_type", "field")
        .agg(pl.len().alias("n"), pl.col("time").min().alias("from"), pl.col("time").max().alias("to"))
    )
    patterns = (
        per_device.group_by("change_type", "field", "n", "from", "to")
        .agg(pl.col("device_id").sort().alias("devices"))
        .with_columns(_short_time("from"), _short_time("to"), pl.col("devices").list.len().alias("device_count"))
        .sort("change_type", "field", "device_count", nulls_last=True, descending=[False, False, True])
    )
    lines = ["| Change | Field | Per device | Readings from | to | Devices |", "|---|---|---|---|---|---|"]
    lines += [f"| {r['change_type']} | {_md_cell(r['field'])} | {r['n']} | {r['from']} | {r['to']} | "
              f"{r['device_count']}: {', '.join(r['devices'])} |" for r in patterns.iter_rows(named=True)]
    if rows.filter(pl.col("change_type") == "recomputed").height:
        lines += ["", "A *recomputed* reading is not an edited value: an older reading arrived late and was slotted "
                  "in before it, so its derived gap to the previous reading (`hours_delta`/`elapsed_hours`) was recalculated."]
    return lines


def _detail_changes(rows: pl.DataFrame, names: dict[str, str] | None = None) -> list[str]:
    names = names or {}
    lines = ["| Change | Record | Field | Was | Now |", "|---|---|---|---|---|"]
    for r in rows.iter_rows(named=True):
        label = r["record_key"] if r["record_key"] not in names else f"{r['record_key']} ({names[r['record_key']]})"
        lines.append(f"| {r['change_type']} | {_md_cell(label)} | {_md_cell(r['field'])} | {_md_cell(r['old_value'])} | "
                     f"{_md_cell(r['new_value'])} |")
    return lines


def _changes_section(changes: pl.DataFrame, summary: dict, device_names: dict[str, str]) -> list[str]:
    lines = ["## What changed since the previous run", ""]
    if changes.is_empty():
        return lines + ["Nothing. Every clean record is identical to the previous run.", ""]
    lines += ["| Table | Added | Removed | Changed (records) | Recomputed only (records) |", "|---|---|---|---|---|"]
    lines += [f"| {t} | {c.get('added', 0)} | {c.get('removed', 0)} | {c.get('changed', 0)} | {c.get('recomputed', 0)} |"
              for t, c in summary.items()]
    lines += ["", "*Recomputed* = a value worked out from others (e.g. the gap to the previous reading, a device's version count) "
              "changed because something it depends on changed."]
    for table in summary:
        rows = changes.filter(pl.col("table_name") == table)
        lines += ["", f"### {table}", ""]
        if table == "readings":
            lines += _readings_changes(rows)
        else:
            lines += _detail_changes(rows, device_names if table == "devices" else None)
    return lines + [""]


def _matching_section(devices: pl.DataFrame, machines: pl.DataFrame) -> list[str]:
    if devices.is_empty():
        return ["## Device to machine matching", "", "No FieldTrax devices loaded yet.", ""]
    methods = devices.group_by("link_method").len().sort("link_method", nulls_last=True)
    lines = ["## Device to machine matching", "",
             "Matched by VIN first, then rego, then business + fleet number in the device name.", ""]
    lines += [f"- {r['link_method'] or 'no match'}: {r['len']}" for r in methods.iter_rows(named=True)]
    unmatched = devices.filter(pl.col("machine_id").is_null())
    lines += ["", f"### Devices that match nothing ({unmatched.height})", ""]
    if unmatched.height:
        lines += ["| Device | Name | VIN | Rego | Still listed | Why |", "|---|---|---|---|---|---|"]
        lines += [f"| {r['device_id']} | {_md_cell(r['name'])} | {_md_cell(r['vin_raw'])} | {_md_cell(r['rego_raw'])} | "
                  f"{'yes' if r['is_listed'] else 'no'} | VIN, rego and name match no line on BE Plant or NH Fleet |"
                  for r in unmatched.iter_rows(named=True)]
    tracked = devices.filter(pl.col("machine_id").is_not_null()).select("machine_id").unique()
    untracked = machines.filter(pl.col("status").is_in(ACTIVE_MACHINE_STATUSES)).join(tracked, on="machine_id", how="anti")
    lines += ["", f"### Working machines with no device ({untracked.height})", ""]
    if untracked.height:
        lines += ["| Machine | Business | Fleet no | Status | Register line |", "|---|---|---|---|---|"]
        lines += [f"| {r['machine_id']} | {r['business_code']} | {r['fleet_no']} | {r['status']} | "
                  f"{r['source_tab']}!{r['source_row']} |" for r in untracked.sort("business_code", "fleet_no").iter_rows(named=True)]
    return lines + [""]


def render_changes_markdown(changes: pl.DataFrame, tables: dict[str, pl.DataFrame], result) -> str:
    lines = ["# FieldTrax sync and record changes", "", f"Run `{result.run_id}`.", ""]
    lines += _sync_section(result)
    names = dict(tables["devices"].select("device_id", "name").iter_rows()) if tables["devices"].height else {}
    lines += _changes_section(changes, result.change_summary, names)
    lines += _matching_section(tables["devices"], tables["machines"])
    return "\n".join(lines)
